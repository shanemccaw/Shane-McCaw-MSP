#!/usr/bin/env node
/**
 * #1846 — Render the "$metadata is not complete" persistence section of
 * docs/graph-resource-model.md from the live `config_resource_property_divergence` table.
 *
 * Generated, not hand-written: this script is the only thing that should ever edit the
 * text between the BEGIN/END markers below. Re-run it any time after
 * `verify-sample.mjs` (which calls the detector itself, so this just re-renders the doc
 * from whatever the detector most recently persisted) to keep the doc in sync with the
 * database rather than frozen at 2026-08-30's six findings.
 *
 * Does NOT touch #1794's original "Finding: $metadata is not complete" section further
 * up the same doc — that stays as the historical record of the first extraction. This
 * section is the durable, re-derivable twin of it.
 *
 * Usage: node scripts/config-state/render-property-divergence-doc.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { connect } from "./db.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DOC_PATH = path.join(repoRoot, "docs", "graph-resource-model.md");

const BEGIN_MARKER = "<!-- BEGIN: generated by scripts/config-state/render-property-divergence-doc.mjs (Git #1846) -->";
const END_MARKER = "<!-- END: generated by scripts/config-state/render-property-divergence-doc.mjs (Git #1846) -->";

const isoDate = (d) => (d instanceof Date ? d.toISOString() : String(d));

function renderSection({ rows, generatedAt }) {
  const versionGap = rows.filter((r) => r.divergence_class === "version_gap");
  const undeclared = rows.filter((r) => r.divergence_class === "undeclared_anywhere");

  const lines = [];
  lines.push(BEGIN_MARKER);
  lines.push("");
  lines.push("## #1846 — Persisting the $metadata-vs-observed divergence (generated)");
  lines.push("");
  lines.push(
    "The \"Finding\" section above records what the 2026-08-30 extraction found; it is a "
    + "point-in-time doc edit and is left as-is. This section is its durable twin: generated "
    + "from `config_resource_property_divergence`, a table "
    + "`scripts/config-state/detect-property-divergence.mjs` recomputes every time "
    + "`verify-sample.mjs` runs, so a property Graph starts returning after this date shows up "
    + "here on the next sample rather than needing someone to remember to re-run a query.",
  );
  lines.push("");
  lines.push(
    `As of the last detection run (${generatedAt}): **${rows.length} observed-but-undeclared `
    + `properties** across the whole sampled surface — **${versionGap.length} version_gap**, `
    + `**${undeclared.length} undeclared_anywhere**.`,
  );
  lines.push("");
  lines.push(
    "Two classes, because they carry different implications for #1795's snapshot store:",
  );
  lines.push("");
  lines.push(
    "- **`version_gap`** — declared in the *other* Graph version's `$metadata` (in every case "
    + "observed so far, beta declares it and v1.0 does not), just not the version this resource "
    + "is actually read under. A versioning gap, not a surprise: Microsoft published it "
    + "somewhere.",
  );
  lines.push(
    "- **`undeclared_anywhere`** — declared in **neither** v1.0 nor beta `$metadata`. Graph is "
    + "returning something no published CSDL document describes at all. This is the class "
    + "nobody can anticipate from reading `$metadata`, and the reason this table exists.",
  );
  lines.push("");

  if (versionGap.length > 0) {
    lines.push("### `version_gap` — declared elsewhere, not here");
    lines.push("");
    lines.push("| Resource | Property | Declared in | Observed type | First seen | Last confirmed |");
    lines.push("|---|---|---|---|---|---|");
    for (const r of versionGap) {
      lines.push(
        `| \`${r.resource_key}\` | \`${r.property_name}\` | ${r.declared_in_graph_versions.join(", ")} `
        + `| ${r.observed_json_type ?? "—"} | ${isoDate(r.first_observed_at)} | ${isoDate(r.last_observed_at)} |`,
      );
    }
    lines.push("");
  }

  if (undeclared.length > 0) {
    lines.push("### `undeclared_anywhere` — Graph returning something no `$metadata` describes");
    lines.push("");
    lines.push("| Resource | Property | Observed type | First seen | Last confirmed |");
    lines.push("|---|---|---|---|---|");
    for (const r of undeclared) {
      lines.push(
        `| \`${r.resource_key}\` | \`${r.property_name}\` | ${r.observed_json_type ?? "—"} `
        + `| ${isoDate(r.first_observed_at)} | ${isoDate(r.last_observed_at)} |`,
      );
    }
    lines.push("");
  }

  if (rows.length === 0) {
    lines.push(
      "*No divergence currently on record.* Either nothing has been observed to diverge from "
      + "`$metadata` in the latest sample, or `config_resource_samples` is currently empty (see "
      + "#1895 — `build-resource-model.mjs` wipes it on every rebuild) and "
      + "`verify-sample.mjs` has not been re-run since. Re-run `verify-sample.mjs` to refresh.",
    );
    lines.push("");
  }

  lines.push(
    "**Not fixed, on purpose.** None of the properties above were added to "
    + "`config_resource_properties` as though `$metadata` declared them — doing so would erase "
    + "the very distinction this table exists to preserve. #1795's snapshot store is the place "
    + "this changes behavior: it must stay open (store the real response object), never typed "
    + "or filtered strictly to the declared property set.",
  );
  lines.push("");
  lines.push("Reproduce or extend the check:");
  lines.push("");
  lines.push("```bash");
  lines.push("node scripts/config-state/verify-sample.mjs          # live sample + detection, wired together");
  lines.push("node scripts/config-state/detect-property-divergence.mjs   # re-detect only, from the existing sample");
  lines.push("```");
  lines.push("");
  lines.push("```sql");
  lines.push("SELECT resource_key, property_name, divergence_class, declared_in_graph_versions,");
  lines.push("       observed_json_type, observation_count, last_observed_at");
  lines.push("  FROM config_resource_property_divergence");
  lines.push(" ORDER BY divergence_class, resource_key, property_name;");
  lines.push("```");
  lines.push("");
  lines.push(END_MARKER);
  return lines.join("\n");
}

async function main() {
  const client = await connect();
  try {
    const { rows } = await client.query(
      `SELECT resource_key, property_name, divergence_class, declared_in_graph_versions,
              observed_json_type, first_observed_at, last_observed_at, observation_count
         FROM config_resource_property_divergence
        ORDER BY divergence_class, resource_key, property_name`);

    const generatedAt = new Date().toISOString();
    const section = renderSection({ rows, generatedAt });

    const rawDoc = await readFile(DOC_PATH, "utf8");
    const usesCrlf = rawDoc.includes("\r\n");
    // Normalize to \n while editing so string search/marker logic isn't CRLF-sensitive;
    // restore CRLF on write since the rest of the file uses it (git's core.autocrlf).
    const doc = rawDoc.replace(/\r\n/g, "\n");
    const beginIdx = doc.indexOf(BEGIN_MARKER);
    const endIdx = doc.indexOf(END_MARKER);

    let next;
    if (beginIdx !== -1 && endIdx !== -1) {
      next = doc.slice(0, beginIdx) + section + doc.slice(endIdx + END_MARKER.length);
    } else {
      // First run: insert before "## Running it", the same seam #1865's dated section
      // was added before, keeping the reference tail (Running it / Reading it / Known
      // limits) last.
      const anchor = "\n## Running it\n";
      const anchorIdx = doc.indexOf(anchor);
      if (anchorIdx === -1) throw new Error(`anchor "${anchor.trim()}" not found in ${DOC_PATH}`);
      next = doc.slice(0, anchorIdx) + "\n" + section + "\n" + doc.slice(anchorIdx);
    }

    await writeFile(DOC_PATH, usesCrlf ? next.replace(/\n/g, "\r\n") : next, "utf8");
    console.log(`Rendered ${rows.length} divergence rows into ${path.relative(repoRoot, DOC_PATH)}`);
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  console.error(`render-property-divergence-doc failed: ${err.stack ?? err.message}`);
  process.exit(1);
});
